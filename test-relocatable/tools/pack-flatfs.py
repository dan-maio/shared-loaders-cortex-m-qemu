#!/usr/bin/env python3
# pack-flatfs.py <out.c> <symbol> <name1=file1> <name2=file2> ...
# Pack several .rel.o into ONE flat-fs archive, emitted as a const flash array.
#
# Archive layout (little-endian, data 8-aligned):
#   magic   "FLFS"                     (4 bytes)
#   count   u32                        (number of entries)
#   entries count * { name[16], u32 offset, u32 size }   (offset from archive start)
#   ...pad to 8...
#   data    each module's bytes, each padded to 8
import sys, struct
out, sym = sys.argv[1], sys.argv[2]
items = [(a.split("=", 1)[0], open(a.split("=", 1)[1], "rb").read()) for a in sys.argv[3:]]
align8 = lambda n: (n + 7) & ~7

off = align8(8 + 24 * len(items))              # data starts after padded directory
entries, data = [], bytearray()
for name, blob in items:
    entries.append((name, off, len(blob)))
    data += blob + b"\x00" * (align8(len(blob)) - len(blob))
    off += align8(len(blob))

ar = bytearray(b"FLFS") + struct.pack("<I", len(items))
for name, o, s in entries:
    ar += name.encode()[:16].ljust(16, b"\x00") + struct.pack("<II", o, s)
ar += b"\x00" * (align8(len(ar)) - len(ar))    # pad dir to data start
ar += data

with open(out, "w") as f:
    f.write("/* flat-fs archive of %d modules - generated by pack-flatfs.py */\n" % len(items))
    f.write("__attribute__((aligned(8))) const unsigned char %s[] = {\n" % sym)
    for i in range(0, len(ar), 16):
        f.write("  " + ",".join("0x%02x" % b for b in ar[i:i+16]) + ",\n")
    f.write("};\nconst unsigned %s_len = %d;\n" % (sym, len(ar)))
print("packed %d modules (%d bytes) -> %s" % (len(items), len(ar), out))
