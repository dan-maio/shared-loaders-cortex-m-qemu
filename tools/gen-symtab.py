#!/usr/bin/env python3
"""gen-symtab.py — Extract symbols from an ELF and generate a C symbol table.

Usage: python3 gen-symtab.py <firmware.elf> <output.c>

Generates a C file with an array of {name, address} pairs for runtime symbol resolution.
Only exports function symbols (STT_FUNC) and data symbols (STT_OBJECT) that are defined
(not UND) and have non-zero addresses.
"""
import subprocess
import sys
import os

def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <firmware.elf> <output.c>", file=sys.stderr)
        sys.exit(1)

    elf_path = sys.argv[1]
    output_path = sys.argv[2]

    # Find nm
    nm = None
    for candidate in ["arm-none-eabi-nm", "nm"]:
        try:
            subprocess.run([candidate, "--version"], capture_output=True, check=True)
            nm = candidate
            break
        except (FileNotFoundError, subprocess.CalledProcessError):
            continue
    if not nm:
        print("Error: nm not found", file=sys.stderr)
        sys.exit(1)

    # Run nm to get symbols
    result = subprocess.run(
        [nm, "-C", "-n", elf_path],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print(f"Error running nm: {result.stderr}", file=sys.stderr)
        sys.exit(1)

    symbols = []
    seen = set()
    for line in result.stdout.strip().split('\n'):
        if not line.strip():
            continue
        parts = line.split(None, 2)
        if len(parts) < 3:
            continue
        addr_str, sym_type, name = parts
        try:
            addr = int(addr_str, 16)
        except ValueError:
            continue
        if addr == 0:
            continue
        # Only export defined symbols (not UND)
        if sym_type in ('U', 'u', 'w', 'W'):
            continue
        # Skip internal symbols
        if name.startswith('_') and not name.startswith('__'):
            continue
        # Skip Thumb bit (bit 0) for function addresses
        if sym_type in ('t', 'T'):
            addr_clean = addr & ~1
        else:
            addr_clean = addr
        if name in seen:
            continue
        seen.add(name)
        # Escape special characters for C string
        name_escaped = name.replace('\\', '\\\\').replace('"', '\\"')
        symbols.append((name_escaped, addr_clean))

    # Generate C file
    os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)
    with open(output_path, 'w') as f:
        f.write('/* Auto-generated by gen-symtab.py — DO NOT EDIT */\n')
        f.write('#include <stdint.h>\n\n')
        f.write('struct sym_entry { const char* name; uint32_t addr; };\n\n')
        f.write('static const struct sym_entry g_symtab[] = {\n')
        for name, addr in symbols:
            f.write(f'    {{"{name}", 0x{addr:08X}}},\n')
        f.write('};\n\n')
        f.write('static const unsigned g_symtab_count = sizeof(g_symtab) / sizeof(g_symtab[0]);\n\n')
        f.write('/* Called by link_context to resolve symbols at runtime */\n')
        f.write('uint32_t symtab_lookup(const char* name) {\n')
        f.write('    for (unsigned i = 0; i < g_symtab_count; ++i) {\n')
        f.write('        const char* a = g_symtab[i].name;\n')
        f.write('        const char* b = name;\n')
        f.write('        while (*a && *b && *a == *b) { ++a; ++b; }\n')
        f.write('        if (*a == *b) return g_symtab[i].addr;\n')
        f.write('    }\n')
        f.write('    return 0;\n')
        f.write('}\n')

    print(f"Generated {len(symbols)} symbols -> {output_path}")

if __name__ == '__main__':
    main()
